package com.yoruc.mangacracker.core

/**
 * Content guard. Titles tagged as sexual content involving minors are always hidden (not a setting);
 * the user's own hidden tags from Settings are added on top.
 */
object Safety {
    /** Always hidden, on every source (after lower-casing, '_' and '-' read as spaces, namespace dropped). */
    private val HARD = setOf(
        "loli", "lolicon", "shota", "shotacon", "shoutacon", "toddlercon", "oppai loli", "petite loli", "low loli", "low shotacon",
        "low lolicon", "ijime loli", "underage", "underage uke", "underage seme", "kodomo doushi", "legal loli", "legal shota",
        "loli protagonist", "loli female lead", "lolicon protagonist", "shota protagonist", "shota uke", "shota seme",
        "shota character/s", "loli/grooming/child porn", "child rape", "child sexual abuse", "child pornography", "child prostitute",
    )

    /**
     * Words that also describe ordinary stories ("Age Regression" isekai, a "Child Protagonist"): they hide a title
     * only when it is 18+, and always on the 18+ picture / doujin sources.
     */
    private val SOFT = setOf(
        "child", "children", "child/ren", "kid", "kids", "minor", "young", "young girl", "young boy", "infant", "baby",
        "toddler", "lolita", "lolita/s", "elementary school student", "elementary school student/s", "elementary schooler",
        "elementary school", "preschooler", "kindergartener", "kindergarten", "cub", "aged down", "age regression",
        "female child", "male child", "kindergarten uniform", "randoseru", "child protagonist",
    )

    /** Mainstream manga sources, where SOFT words only count on 18+ titles. */
    private val MAINSTREAM = setOf("atsu", "comix", "jestful")
    private val ADULT_MARKS = setOf("adult", "hentai", "smut", "pornographic", "erotica", "rating:e", "rating:q", "rating:explicit", "rating:questionable")

    @Volatile var userHidden: Set<String> = emptySet()

    /** Settings "Hide AI-generated" (on by default): AI tags and titles that say they are AI made. */
    @Volatile var hideAi: Boolean = true

    /** AI tags as the sites spell them (nhentai / hitomi / e-hentai "ai generated", boorus "ai-generated", ...). */
    private val AI_TAGS = setOf(
        "ai generated", "ai generated art", "ai generated content", "aigenerated", "ai art", "ai artwork", "ai assisted",
        "ai created", "ai cg", "stable diffusion", "novelai", "novel ai", "nai diffusion", "midjourney", "nijijourney",
    )

    /**
     * Titles: "[AI Generated]", "AI-generated", "generated by AI", "[AI]" / "(AI Art)" in brackets, "AI生成".
     * A bare "Ai" is a common name, so outside these phrases it never counts (and in brackets only as capital "AI").
     */
    private val AI_TITLE = Regex("\\bA\\.?I\\.?[\\s_\\-]*generated\\b|\\bgenerated\\s+(?:by|with|using)\\s+A\\.?I\\b", RegexOption.IGNORE_CASE)
    private val AI_BRACKET = Regex("[\\[(（【]\\s*AI(?:[\\s_\\-]*(?:[Aa]rt|ART|[Gg]en|GEN|[Aa]ssisted|CG|[Ii]llust\\w*|[Mm]ade))?\\s*[\\])）】]|AI\\s*(?:生成|作画|作畫|绘|繪|画|畫|イラスト)")

    fun isAiTag(tag: String): Boolean = norm(tag) in AI_TAGS
    fun isAiTitle(title: String): Boolean = AI_TITLE.containsMatchIn(title) || AI_BRACKET.containsMatchIn(title)

    /** Settings "Hide futanari" / "Hide furry" (on by default), for manga, pictures and videos. */
    @Volatile var hideFuta: Boolean = true
    @Volatile var hideFurry: Boolean = true

    /** Tags (after [norm]): futanari / dickgirl in any form ("futa on male", "female:futanari"); not "futari" (= two people). */
    private val FUTA_TAG = Regex("\\bfuta(?:nari)?s?\\b|\\bdickgirls?\\b")
    /** furry / anthro / yiff in any form ("human on furry", "furry female"); not animal ears (kemonomimi) or "anthropomorphic". */
    private val FURRY_TAG = Regex("\\bfurry\\b|\\bfurries\\b|\\banthro\\b|\\byiff\\b")
    private val FUTA_TITLE = Regex("\\bfutanari\\b|\\bfuta\\b|\\bdickgirls?\\b|ふたなり|扶他", RegexOption.IGNORE_CASE)
    private val FURRY_TITLE = Regex("\\bfurry\\b|\\bfurries\\b|\\byiff\\b", RegexOption.IGNORE_CASE)

    fun isFutaTag(tag: String): Boolean = FUTA_TAG.containsMatchIn(norm(tag))
    fun isFurryTag(tag: String): Boolean = FURRY_TAG.containsMatchIn(norm(tag))

    /** A tag hidden by one of the switches. [ai] = false for videos (the AI switch is for reading only). */
    fun optTag(tag: String, ai: Boolean = true): Boolean =
        (ai && hideAi && isAiTag(tag)) || (hideFuta && isFutaTag(tag)) || (hideFurry && isFurryTag(tag))

    /** A title hidden by one of the switches (the same words as the tags, plus AI's own title phrases). */
    fun optTitle(title: String, ai: Boolean = true): Boolean =
        (ai && hideAi && isAiTitle(title)) || (hideFuta && FUTA_TITLE.containsMatchIn(title)) || (hideFurry && FURRY_TITLE.containsMatchIn(title))

    /** What a switch hides a title for ("AI-generated", "futanari", "furry"), for the title page's message; null if none. */
    fun switchReason(d: MangaDetails): String? {
        val titles = listOf(d.ref.title) + d.altTitles
        val tags = d.genres + d.ref.tags + d.tagGroups.flatMap { it.tags }
        return when {
            hideAi && (titles.any { isAiTitle(it) } || tags.any { isAiTag(it) }) -> "AI-generated"
            hideFuta && (titles.any { FUTA_TITLE.containsMatchIn(it) } || tags.any { isFutaTag(it) }) -> "futanari"
            hideFurry && (titles.any { FURRY_TITLE.containsMatchIn(it) } || tags.any { isFurryTag(it) }) -> "furry"
            else -> null
        }
    }

    fun norm(tag: String): String =
        tag.substringAfter(':').lowercase().replace('_', ' ').replace('-', ' ').replace(Regex("\\s+"), " ").trim()

    /** For tag pickers: never offer any of these. */
    fun isMinorTag(tag: String): Boolean = norm(tag).let { it in HARD || it in SOFT }

    private fun isAdult(tags: Collection<String>) = tags.any { t -> t.lowercase() in ADULT_MARKS || norm(t) in ADULT_MARKS }

    fun blocked(tags: Collection<String>, source: String = ""): Boolean {
        val strictSoft = source !in MAINSTREAM || isAdult(tags)
        return tags.any { t ->
            val n = norm(t)
            n in HARD || n in userHidden || (strictSoft && n in SOFT) || optTag(t)
        }
    }

    fun blocked(ref: MangaRef): Boolean = blocked(ref.tags, ref.source) || optTitle(ref.title)

    fun blocked(d: MangaDetails): Boolean = blocked(d.genres + d.ref.tags + d.tagGroups.flatMap { it.tags }, d.ref.source) || switchReason(d) != null

    /** Hidden only because it is AI made (for the title page's message). */
    fun isAi(d: MangaDetails): Boolean = hideAi &&
        (isAiTitle(d.ref.title) || d.altTitles.any { isAiTitle(it) } || (d.genres + d.ref.tags + d.tagGroups.flatMap { it.tags }).any { isAiTag(it) })

    fun filter(items: List<MangaRef>): List<MangaRef> = items.filterNot { blocked(it) }
    fun filter(r: PageResult): PageResult = r.copy(items = filter(r.items))

    /** Tags offered in filter sheets: never list the minor ones (nor the ones a switch hides). */
    fun cleanTags(tags: List<Tag>): List<Tag> =
        tags.filterNot { isMinorTag(it.label) || isMinorTag(it.id) || optTag(it.label) || optTag(it.id) }
}
