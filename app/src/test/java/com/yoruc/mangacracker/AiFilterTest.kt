package com.yoruc.mangacracker

import com.yoruc.mangacracker.core.MangaRef
import com.yoruc.mangacracker.core.Safety
import com.yoruc.mangacracker.core.SearchQuery
import com.yoruc.mangacracker.sources.Sources
import com.yoruc.mangacracker.video.VideoRef
import com.yoruc.mangacracker.video.VideoSafety
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * "Hide AI-generated" (manga / pictures only, videos untouched): the title / tag rules on their own, then every source live (latest + a search for "ai
 * generated"): how many cards it hides, the words that hid them, any "AI" left in a visible title (to judge by eye),
 * and the first visible titles opened to see whether their tags say AI after all. Whole titles are never printed.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class AiFilterTest {
    private val pick = System.getProperty("sources").orEmpty().split(',').map { it.trim() }.filter { it.isNotEmpty() }.toSet()
    private fun log(s: String) = println("[ai] $s")

    @Test fun rules() {
        Safety.hideAi = true
        val yes = listOf(
            "[AI Generated] Something", "Something [AI generated]", "(AI-Generated) X", "x ai generated y", "AIGenerated pack",
            "[AI] Title", "Title (AI Art)", "【AI】 Title", "[AI Gen] Title", "Made AI生成 set", "generated by AI", "A.I. generated",
        )
        val no = listOf(
            "Ai's Secret", "Ai-chan no Himitsu", "[Ai] circle", "Kaori and Ai", "Aihara Mei", "Main Character", "Said Generated",
            "Hoshino Ai", "Ai Generation Gap", "MAI generated", "Paint (Ai)", "Domestic na Kanojo", "[Aino] Title",
        )
        yes.forEach { assertTrue("should hide: $it", Safety.isAiTitle(it)) }
        no.forEach { assertTrue("should keep: $it", !Safety.isAiTitle(it)) }
        listOf("ai generated", "ai-generated", "other:ai generated", "AI_Generated", "ai art", "stable diffusion", "novelai").forEach {
            assertTrue("tag $it", Safety.isAiTag(it))
        }
        listOf("ai (character)", "hoshino ai", "ai", "aikatsu", "paint").forEach { assertTrue("tag kept $it", !Safety.isAiTag(it)) }
        val r = MangaRef("nhentai", "1", "[AI Generated] X")
        assertTrue(Safety.blocked(r))
        assertTrue(Safety.blocked(r.copy(title = "Ok", tags = listOf("ai generated"))))
        assertTrue("videos are not AI-filtered", !VideoSafety.blocked(VideoRef("x", "1", "Clip [AI Generated]")))
        Safety.hideAi = false
        assertTrue(!Safety.blocked(r))
        Safety.hideAi = true
        assertEquals(1, Safety.cleanTags(listOf(com.yoruc.mangacracker.core.Tag("ai-generated", "AI Generated"), com.yoruc.mangacracker.core.Tag("x", "Big"))).size)
    }

    /** Text around a stand-alone "AI" (any case), so missed spellings can be read without the rest of the title. */
    private fun aiBits(t: String) = Regex("(?i)(?<![a-z])a\\.?i(?![a-z])").findAll(t)
        .map { t.substring((it.range.first - 12).coerceAtLeast(0), (it.range.last + 14).coerceAtMost(t.length)) }.toList()

    private fun hideWhy(t: String) = Regex("(?i)\\bA\\.?I\\.?[\\s_\\-]*generated\\b|generated\\s+(by|with|using)\\s+A\\.?I|[\\[(（【]\\s*AI[^\\])）】]{0,12}[\\])）】]|AI\\s*\\S")
        .find(t)?.value ?: "(tag)"

    @Test fun live() {
        Safety.hideAi = true
        var err: Throwable? = null
        val th = Thread {
            runCatching {
                runBlocking {
                    for (s in Sources.all.filter { (pick.isEmpty() || it.id in pick) && it.id !in setOf("comix", "ehentai") }) {
                        // the site's own AI tag when it has one (searched with the switch off, so the sources' own
                        // tag cleaning keeps it), else the words
                        Safety.hideAi = false
                        val aiTag = runCatching { s.suggestTags("ai generated") }.getOrDefault(emptyList()).firstOrNull { Safety.isAiTag(it.label) || Safety.isAiTag(it.id) }
                        Safety.hideAi = true
                        if (aiTag != null) {
                            // what the user would see searching the AI tag with the switch on: should be nothing
                            val on = runCatching { Safety.filter(s.search(SearchQuery(include = listOf(aiTag)), 1).items) }
                            log("${s.id} AI tag searched with the switch on: ${on.getOrNull()?.size ?: on.exceptionOrNull()?.javaClass?.simpleName} cards shown")
                        }
                        for ((what, get) in listOf<Pair<String, suspend () -> List<MangaRef>>>(
                            "latest" to { s.latest(1).items },
                            (if (aiTag != null) "search tag" else "search words") to {
                                s.search(if (aiTag != null) SearchQuery(include = listOf(aiTag)) else SearchQuery(text = "ai generated"), 1).items
                            },
                        )) {
                            Safety.hideAi = false
                            val got = runCatching { get() }
                            Safety.hideAi = true
                            got.exceptionOrNull()?.let { log("${s.id} $what: ${it.javaClass.simpleName} ${it.message?.take(80)}") }
                            val all = got.getOrNull() ?: continue
                            val shown = Safety.filter(all)
                            val hid = all - shown.toSet()
                            log("${s.id} $what: ${all.size} cards, hidden AI ${hid.count { Safety.isAiTitle(it.title) || it.tags.any(Safety::isAiTag) }}" +
                                " (other filters ${hid.count { !Safety.isAiTitle(it.title) && it.tags.none(Safety::isAiTag) }})")
                            hid.filter { Safety.isAiTitle(it.title) }.map { hideWhy(it.title) }.groupingBy { it }.eachCount().forEach { (k, n) -> log("    hid by '$k' x$n") }
                            shown.flatMap { aiBits(it.title) }.take(8).forEach { log("    visible AI word: …$it…") }
                            if (what.startsWith("search")) {
                                var leak = 0; var opened = 0
                                for (r in shown.take(5)) {
                                    Safety.hideAi = false
                                    val d = runCatching { s.details(r) }.getOrNull()
                                    Safety.hideAi = true
                                    if (d == null) continue
                                    opened++
                                    if (Safety.isAi(d)) leak++
                                }
                                log("    opened $opened visible results: $leak are AI by their page tags")
                            }
                        }
                    }
                }
            }.onFailure { err = it }
        }
        th.start()
        val until = System.currentTimeMillis() + 25 * 60_000
        while (th.isAlive && System.currentTimeMillis() < until) { Thread.sleep(50); org.robolectric.shadows.ShadowLooper.idleMainLooper() }
        err?.let { throw it }
    }
}
